import { chromium, expect } from '../../usefultools-frontend/node_modules/@playwright/test/index.mjs'
import { THEME_OPTIONS } from '../../usefultools-frontend/src/theme/themeOptions.js'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
const [run, phase] = process.argv.slice(2)
assert(['before', 'after'].includes(phase))
const root = (await readFile('.local/polish-current.txt', 'utf8')).trim(), output = path.join(root, phase)
await mkdir(output)
const sessions = JSON.parse(await readFile(path.join(run, 'sessions.json'), 'utf8')), origin = sessions.origin
assert(['127.0.0.1', 'localhost'].includes(new URL(origin).hostname))
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const rows = [], fields = [], bundles = {}, errors = [], external = [], scans = []
const modules = [
  ['schema', 'Schema generator', 'Validate and generate schema'],
  ['migration', 'Migration planner', 'Generate migration'],
  ['view', 'View generator', 'Generate view'],
  ['evaluator', 'Schema evaluator', 'Evaluate schema'],
  ['etl', 'Python ETL generator', 'Generate ETL preview'],
  ['rest', 'Java auth starter', 'Generate auth preview'],
  ['rest', 'Python auth starter', 'Generate auth preview'],
]
try {
 const context = await browser.newContext({ viewport: { width: 1440, height: 900 } }), identity = sessions.browseruser
 await context.addCookies([{ name: 'JSESSIONID', value: identity.session, url: origin, httpOnly: true }])
 await context.addInitScript(i => { localStorage.setItem('username', i.username); localStorage.setItem('_ut_role', i.role); sessionStorage.setItem('_ut_xsrf', i.csrf) }, identity)
 await context.route('**/*', route => { if (new URL(route.request().url()).origin !== origin) { external.push(route.request().url()); return route.abort() } return route.continue() })
 await context.route('**/__polish/axe.js', route => route.fulfill({ path: path.resolve('.b7/tools/node_modules/axe-core/axe.min.js'), contentType: 'application/javascript' }))
 const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message))
 await page.goto(origin + '/backend-support', { waitUntil: 'networkidle' })
 for (const [module, name, action] of modules) {
  await page.getByRole('combobox', { name: 'Tool family', exact: true }).selectOption(module)
  if (name === 'Python auth starter') await page.getByRole('combobox', { name: 'Auth target', exact: true }).selectOption('python')
  const region = page.getByRole('region', { name, exact: true }); await expect(region).toBeVisible()
  // Synthetic sample only: its known append-column plan requires explicit review.
  if (module === 'migration') await region.getByRole('checkbox', { name: /External dependencies reviewed/ }).check()
  const inventory = await region.locator('input:not([type=checkbox]), textarea').evaluateAll(es => es.map(e => ({ label: e.getAttribute('aria-label') || [...e.labels].map(l => l.textContent.trim()).join(' '), type: e.type, readOnly: e.readOnly, disabled: e.matches(':disabled'), value: e.value })))
  fields.push({ name, inventory })
  const response = page.waitForResponse(r => r.url().endsWith('/backend-support/generate'))
  await region.getByRole('button', { name: action, exact: true }).click()
  const data = await (await response).json(); assert(data.success, JSON.stringify({ name, data })); bundles[name] = { digest: data.data.digest, files: data.data.files }
  if (phase === 'after') {
   const baseline = JSON.parse(await readFile(path.join(root, 'before/results.json'), 'utf8'))
   assert.deepEqual(bundles[name], baseline.bundles[name], name + ' generated bytes differ')
   assert.deepEqual(inventory, baseline.fields.find(f => f.name === name).inventory, name + ' text fields/defaults changed')
  }
  const resultPreview = region.locator('textarea[readonly], pre[aria-label]').last()
  if (await resultPreview.count()) { await resultPreview.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(output, `${module}-${name.startsWith('Python auth') ? 'python-' : ''}output.png`) }) }
  for (const width of [1440, 768, 375, 320]) {
   await page.setViewportSize({ width, height: width === 1440 ? 900 : width === 768 ? 1024 : 812 }); await page.evaluate(() => document.fonts.ready)
   await page.evaluate(() => scrollTo(0, 0)); await page.mouse.move(0, 0)
   const bounds = await page.getByRole('heading', { name: 'Backend Support', exact: true }).evaluate(e => { const h = e.closest('section').getBoundingClientRect(); return { left: h.left, right: h.right, width: h.width, viewport: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth + 1 } })
   if (phase === 'after') assert(Math.abs(bounds.left) < 1 && Math.abs(bounds.right - width) < 1 && !bounds.overflow, JSON.stringify({ name, width, bounds }))
   rows.push({ name, width, bounds }); await page.screenshot({ path: path.join(output, `${module}-${name.startsWith('Python auth') ? 'python-' : ''}${width}.png`) })
  }
 }
 if (phase === 'after') {
  await page.getByRole('combobox', { name: 'Tool family', exact: true }).selectOption('schema')
  await expect(page.getByRole('combobox', { name: 'Generator template', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'JSON', exact: true }).click()
  const json = page.getByRole('textbox', { name: 'Schema generation JSON', exact: true })
  const spec = JSON.parse(await json.inputValue()); const oldName = spec.tables[0].name
  spec.tables[0].name = 'polished_customers'; await json.fill(JSON.stringify(spec)); await page.getByRole('button', { name: 'Apply JSON to forms', exact: true }).click()
  await page.getByRole('button', { name: 'Tables', exact: true }).click()
  await page.getByRole('combobox', { name: 'Tool family', exact: true }).selectOption('evaluator')
  await expect(page.getByRole('combobox', { name: 'Rule set', exact: true })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Tool family', exact: true }).selectOption('schema')
  await expect(page.getByRole('textbox', { name: 'Table database name', exact: true })).toHaveValue('polished_customers')
  await page.getByRole('textbox', { name: 'Table database name', exact: true }).fill(oldName)
  await page.getByRole('combobox', { name: /^Schema source/ }).selectOption('sample')
  await expect(page.getByRole('textbox', { name: 'Table database name', exact: true })).toBeDisabled()
  await page.getByRole('combobox', { name: /^Schema source/ }).selectOption('draft')
  await expect(page.getByRole('textbox', { name: 'Table database name', exact: true })).toHaveValue(oldName)
  // Removing a selector must not overwrite imported metadata or bypass server validation.
  for (const [module, label, apply, generate, key] of [
   ['schema', 'Schema generation JSON', 'Apply JSON to forms', 'Validate and generate schema', 'templateVersion'],
   ['evaluator', 'Full evaluator specification JSON', 'Apply evaluator JSON', 'Evaluate schema', 'rulesetVersion'],
  ]) {
   await page.getByRole('combobox', { name: 'Tool family', exact: true }).selectOption(module)
   if (module === 'schema') await page.getByRole('button', { name: 'JSON', exact: true }).click()
   const input = page.getByRole('textbox', { name: label, exact: true }), original = await input.inputValue(), invalid = JSON.parse(original)
   invalid[key] = 'unsupported-imported-version'; await input.fill(JSON.stringify(invalid)); await page.getByRole('button', { name: apply, exact: true }).click()
   const response = page.waitForResponse(r => r.url().endsWith('/backend-support/generate'))
   await page.getByRole('button', { name: generate, exact: true }).click(); assert.equal((await response).status(), 422)
   assert.equal(JSON.parse(await input.inputValue())[key], invalid[key])
   await input.fill(original); await page.getByRole('button', { name: apply, exact: true }).click()
  }
  await page.getByRole('combobox', { name: 'Tool family', exact: true }).selectOption('schema')
  const validation = page.waitForResponse(r => r.url().endsWith('/backend-support/validate'))
  await page.getByRole('button', { name: 'Load and validate sample', exact: true }).click()
  assert((await (await validation).json()).success)
  await expect(page.getByRole('textbox', { name: 'Sample specification', exact: true })).not.toHaveValue('')
  await page.screenshot({ path: path.join(output, 'historical-sample.png') })
  for (const theme of THEME_OPTIONS) {
   await page.evaluate(t => localStorage.setItem('usefultools.theme', t), theme.value); await page.reload({ waitUntil: 'networkidle' })
   await page.addScriptTag({ url: origin + '/__polish/axe.js' }); await page.evaluate(() => document.fonts.ready)
   await page.screenshot({ path: path.join(output, `theme-${theme.value}-320.png`) })
   await page.getByRole('button', { name: 'Validate and generate schema', exact: true }).scrollIntoViewIfNeeded()
   await page.screenshot({ path: path.join(output, `actions-${theme.value}-320.png`) })
   const scan = await page.evaluate(async () => { const r = await axe.run(document.querySelector('main'), { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } }); return { violations: r.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), incomplete: r.incomplete.map(v => v.id) } })
   scans.push({ theme: theme.value, ...scan })
  }
  assert(scans.every(s => !s.violations.length), JSON.stringify(scans))
 }
 assert.deepEqual(errors, []); assert.deepEqual(external, [])
 await writeFile(path.join(output, 'results.json'), JSON.stringify({ status: 'PASS', phase, browser: browser.version(), rows, fields, bundles, scans, errors, external }, null, 2))
 console.log('PASS', phase, rows.length, 'module/viewport captures; seven actual generation responses')
} catch (error) { await writeFile(path.join(output, 'failure.json'), JSON.stringify({ error: String(error), rows, scans, errors, external }, null, 2)); throw error }
finally { await browser.close() }
